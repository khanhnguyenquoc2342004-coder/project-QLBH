export default {
  isLoggedIn: (state) => state.isLoggedIn,
  authInitialized: (state) => state.authInitialized,
  currentUser: (state) => state.currentUser,
  userRole: (state) => state.userRole,
  allPackages: (state) => state.packages,
  packagePage: (state) => state.packagePage,
  allUsers: (state) => state.users,
  cartItems: (state) => state.cartItems,
  cartCount: (state) => state.cartItems.reduce((count, item) => count + item.quantity, 0),
  cartTotal: (state) => state.cartItems.reduce((total, item) => total + Number(item.price) * (1 - Number(item.discountPercent || 0) / 100) * item.quantity, 0),
  myOrders: (state) => state.orders,
  adminOrders: (state) => state.adminOrders,
  dashboardSummary: (state) => state.dashboardSummary,
  auditLogs: (state) => state.auditLogs,
  registrations: (state) => state.registrations,
  purchasedServices: (state) => state.purchasedServices,
  adminRegistrations: (state) => state.adminRegistrations,
  integrationLogs: (state) => state.integrationLogs,
  isLoading: (state) => state.loading,
  error: (state) => state.error,
  canManagePackages: (state) => state.userRole === 'ADMIN',
  canManageUsers: (state) => state.userRole === 'ADMIN',
  isCustomer: (state) => state.userRole === 'CUSTOMER'
};
